/// Password manager spacings.
abstract class PmSpacing {
  const PmSpacing._();

  /// xxs spacing value (0pt)
  static const double xxs = 0;

  /// xs spacing value (2pt)
  static const double xs = 2;

  /// s spacing value (4pt)
  static const double s = 4;

  /// m spacing value (8pt)
  static const double m = 8;

  /// l spacing value (12pt)
  static const double l = 12;

  /// xl spacing value (16pt)
  static const double xl = 16;

  /// xxl spacing value (20pt)
  static const double xxl = 20;

  /// 3xl spacing value (24pt)
  static const double xl3 = 24;

  /// 4xl spacing value (32pt)
  static const double xl4 = 32;

  /// 5xl spacing value (40pt)
  static const double xl5 = 40;
}
