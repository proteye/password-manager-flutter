/// Password manager radius.
abstract class PmRadius {
  const PmRadius._();

  /// xs radius (2pt)
  static const double xs = 2;

  /// s radius (4pt)
  static const double s = 4;

  /// m radius (8pt)
  static const double m = 8;

  /// l radius (16pt)
  static const double l = 16;

  /// xl radius (24pt)
  static const double xl = 24;

  /// xxl full round radius (100pt)
  static const double xxl = 100;
}
