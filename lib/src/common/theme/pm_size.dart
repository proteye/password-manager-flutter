/// Password manager sizes (buttons, icons and others).
abstract class PmSize {
  const PmSize._();

  /// xxs size (12pt)
  static const double xxs = 12;

  /// xs size (16pt)
  static const double xs = 16;

  /// s size (20pt)
  static const double s = 20;

  /// m size (24pt)
  static const double m = 24;

  /// l size (32pt)
  static const double l = 32;

  /// xl size (40pt)
  static const double xl = 40;

  /// xxl size (48pt)
  static const double xxl = 48;

  /// mobile navbar, header size (56pt)
  static const double navbarSmall = 56;

  /// desktop navbar, header size (64pt)
  static const double navbarBig = 64;

  /// small button (20pt)
  static const double btnSmall = 20;

  /// medium button (32pt)
  static const double btnMedium = 32;

  /// big button (48pt)
  static const double btnBig = 48;

  /// FAB button (64pt)
  static const double btnFab = 64;

  /// small icon-button (24pt)
  static const double btnIconSmall = 24;

  /// medium icon-button (32pt)
  static const double btnIconMedium = 32;
}
